'use strict';
const assert=require('node:assert/strict');
const E=require('../engine.js');
const roll=E.randomCharacter(1355150487);
assert.deepEqual(roll,E.randomCharacter(1355150487));
const initial=E.newGame(roll);
assert.equal(initial.player.name,roll.name);
assert.equal(initial.player.family.household,roll.family.household);
assert.equal(initial.player.partnerIds.length,roll.path==='partner'?1:0);
assert.equal(initial.player.meridian.gates.length,0);
assert.equal(initial.player.arcane.circles,0);
assert.deepEqual(E.importGame(E.exportGame(initial)),initial);
const s=E.newGame({name:'Researcher',path:'undecided',seed:121,background:'scholar'});
const D=(q)=>E.dispatch(s,q);
assert.equal(D('research start Murrain screen | method | 2 | variant').ok,true);
assert.equal(s.researchProjects.murrain_screen.dc,15);
assert.equal(s.researchProjects.murrain_screen.track,20);
assert.equal(D('research week murrain_screen').ok,false);
assert.equal(D('research survey murrain_screen').ok,true);
assert.equal(D('research week murrain_screen').ok,true);
assert.equal(s.researchProjects.murrain_screen.weeks,1);
assert.equal(D('travel ruins').ok,false);
assert.equal(D('travel forest').ok,true);
assert.equal(D('explore').ok,true);
assert.equal(D('invite').ok,false);
assert.ok(E.coreHud(s).includes('╔'));
assert.ok(E.recap(s).includes('SCENE:'));
const a=E.newGame({name:'Seed',seed:91}),b=E.newGame({name:'Seed',seed:91});
for(const action of ['travel fen','explore','observe','leave','forage']){assert.equal(E.dispatch(a,action).ok,E.dispatch(b,action).ok);}
assert.deepEqual(a,b);
