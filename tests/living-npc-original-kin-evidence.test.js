'use strict';
// Existing origin-relative identity and original family continuity only.
// No new actor, kinship, family estate, magic, progression, dice or saved campaign.
const A=require('node:assert/strict'),E=require('../engine.js'),
 New=require('../scripts/new-campaign'),
 Kin=require('../world/origin-relatives'),
 Time=require('../rules/world'),Realm=require('../world/simulation'),
 Rules=require('../rules'),
 Foundations=require('../world/person-mechanical-foundations');
const s=New.create({seed:500001,slug:'disposable_existing_family_evidence',
 mode:'guided',homeRegion:'morrowfen_basin',
 startLocation:'crossing',originKind:'ordinary'}).state;
const w=Realm.peek(s),t=Kin.ensure(w);
A.ok(t&&Object.keys(t.people).length);
const p=t.people.kin_1,id=p.actorId;
A.equal(Kin.verify(w,p),true);
const remembered=Kin.status(s).relatives.find(x=>x.npcId===id);
A.ok(remembered);
const snapshot=E.exportGame(s),rng=s.rngState,time=s.world.minutes,
 workerRng=p.rngState;
const evidence=Foundations.earnedEvidence(w,id,s);
const d=Foundations.gmDossier(w,id,s);
A.equal(d.kind,'original-independent-origin-relative');
A.equal(d.privateToGM,true);
A.equal(d.earnedEvidence.originalIdentityHash,p.sourceHash);
A.equal(evidence.name,p.name);
A.equal(evidence.familyRelationship.foundingHouseholdRole,p.relation);
A.equal(evidence.familyRelationship.explicitlyRecordedKinship,p.kinship||null);
A.equal(evidence.familyRelationship.playerConfirmedRelationship,
 remembered.confirmedRelationship,
 'Player-recorded corrections must come through original scene continuity');
A.equal(evidence.familyRelationship.biologicalLineageNotInferred,true);
A.equal(evidence.familyRelationship.noInheritedPowersByKinship,true);
A.equal(evidence.autonomousOrdinaryLife.currentFatigue,p.fatigue);
A.equal(evidence.autonomousOrdinaryLife.currentPersonalFunds,p.funds);
A.equal(evidence.autonomousOrdinaryLife.recentOriginalReceipts.length,0);
A.equal(evidence.noPresenceOrConsentByFamilyRole,true);
A.equal(evidence.currentLocalPresence,null);
A.equal(evidence.ageAndLiveCombatAttributes,null);
A.equal(evidence.supernaturalDisciplineMilestones,null);
A.equal(d.baselineAttributes,null);
A.equal(d.latentPotential,null);
A.equal(E.exportGame(s),snapshot,'Private kin evidence must be read-only');
A.equal(s.rngState,rng);
A.equal(s.world.minutes,time);
A.equal(p.rngState,workerRng);
A.throws(()=>Foundations.gmDossier(w,id),/Matching original game state/);
const wrong=E.importGame(snapshot);
A.throws(()=>Foundations.gmDossier(w,id,wrong),/Matching original game state/);
A.deepEqual(Foundations.gmDossier(w,'origin-kin:kin_999',s),
 {known:false},'Unknown family member is not generated by reading');
const publicStatus=Rules.act(s,{system:'social',
 operation:'originRelativesStatus',params:{}});
A.equal(publicStatus.relatives.length,Object.keys(t.people).length);
A.equal(JSON.stringify(publicStatus).includes('currentPersonalFunds'),false);
A.equal(JSON.stringify(publicStatus).includes('originalIdentityHash'),false);
A.equal(JSON.stringify(publicStatus).includes('supernaturalDisciplineMilestones'),false);
Time.advance(s,13);
const updated=Foundations.gmDossier(Realm.peek(s),id,s).earnedEvidence;
A.ok(p.history.length>0,'Original independent family decisions occur on real world ticks');
A.equal(updated.autonomousOrdinaryLife.recentOriginalReceipts.length,p.history.length);
A.deepEqual(updated.autonomousOrdinaryLife.recentOriginalReceipts,
 p.history.map(e=>({sourceHash:e.hash,day:e.source.day,
  choice:e.source.decision,
  observedOrdinaryFundsBefore:e.source.before?.funds??null,
  observedOrdinaryFundsAfter:e.source.after?.funds??null,
  observedFatigueBefore:e.source.before?.fatigue??null,
  observedFatigueAfter:e.source.after?.fatigue??null
 })));
A.equal(updated.currentLocalPresence,null);
A.equal(updated.supernaturalDisciplineMilestones,null);
const saved=E.exportGame(s),replay=E.importGame(saved);
A.deepEqual(Foundations.gmDossier(Realm.peek(replay),id,replay).earnedEvidence,
 updated,'Existing independent kin evidence must survive engine save replay');
const forgedSource=E.importGame(saved),bad=Realm.peek(forgedSource).originKin.people.kin_1;
bad.source.relation='Invented hidden blood heir';
A.throws(()=>Foundations.gmDossier(Realm.peek(forgedSource),id,forgedSource),
 /Unverified original independent relative|no longer matches/,
 'A forged family relationship must not pass through original verifier');
const forgedActivity=E.importGame(saved),
 badActivity=Realm.peek(forgedActivity).originKin.people.kin_1;
badActivity.history[0].source.after.funds=999;
A.throws(()=>Foundations.gmDossier(Realm.peek(forgedActivity),id,forgedActivity),
 /Unverified original independent relative/,
 'A forged independent kin event must be rejected');
const legacy=E.importGame(snapshot);
delete Realm.peek(legacy).originKin;
A.deepEqual(Foundations.gmDossier(Realm.peek(legacy),id,legacy),{known:false},
 'Older saves without source-established individual relatives remain unknown');
A.equal(E.exportGame(s),saved);
console.log('Living NPC origin kin: source-backed family roles and corrections, independent work, privacy, replay, wrong-game/tamper rejection and no invented powers PASS');
