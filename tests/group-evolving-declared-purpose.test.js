'use strict';
// #18: the ORIGINAL living association can grow beyond its starting prose.
// Examples are test fixtures, not a finite catalogue of organisations.
// A founder revises a public declaration; independent members retain agency.
const A=require('node:assert/strict'),E=require('../engine.js'),
 R=require('../rules'),G=require('../world/emergent-groups');
const s=E.newGame({seed:991247,name:'Disposable Changing Group World',
 path:'undecided'});
const examples=[
 {name:'Fenwater Natural History Circle',
  kind:'open field ecology study society',
  purpose:'Collect practical witnessed wetland observations without imposing duties on neighbours',
  revised:'Study changing river habitats and publicly record conditions that threaten ordinary crossing access',
  reason:'A genuine field season makes river access research more useful than the original limited observation programme'},
 {name:'Lantern Loom Cooperative',
  kind:'voluntary artisan and practical trade collective',
  purpose:'Exchange witnessed craft methods among consenting workers without claiming anyone else’s materials',
  revised:'Share tested weaving designs and maintain a local practical repair workshop when actual materials are available',
  reason:'Independent work and regional wear call for more practical repair and open methods'},
 {name:'Night Heron Neighbours',
  kind:'informal wildlife care and settlement observation circle',
  purpose:'Compare local beast welfare observations and support voluntary humane safety responses',
  revised:'Coordinate voluntary habitat watching and practical animal welfare communication while protecting independent beasts',
  reason:'Members wish to describe a broader lawful care purpose as the nearby habitat changes'}
];
const formed=examples.map(({name,kind,purpose})=>
 R.act(s,{system:'social',operation:'formGroup',
  params:{name,kind,purpose}}));
const w=s.table.realm;
const originalCoins=s.player.coins,originalRng=s.rngState,
 worldRng=w.emergentGroups.rngState,memberRng=w.groupMemberAgency?.rngState;
const oldBodies=formed.map(f=>G.lookup(w,f.id).charter.duty);
const groupId=formed[0].id;
const update=(id,purpose,reason)=>
 R.act(s,{system:'social',operation:'restateGroupPurpose',
  params:{groupId:id,purpose,reason}});
const minutesBefore=s.world.minutes;
A.throws(()=>update('phantom-group',examples[0].revised,examples[0].reason),
 /actually locally present founder|actual locally present founder|Only the actual/);
A.throws(()=>update(groupId,examples[0].purpose,examples[0].reason),
 /has not changed/);
A.equal(s.world.minutes,minutesBefore,
 'preflight must reject nonexistent and identical claims without spending time');
for(let i=0;i<3;i++){
 const start=s.world.minutes;
 const x=update(formed[i].id,examples[i].revised,examples[i].reason);
 A.equal(x.actualMinutes,25);
 A.equal(s.world.minutes-start,25);
 A.equal(x.noOtherMembersBound,true);
 A.equal(x.noLegalOfficeOrFundsGranted,true);
 A.equal(G.lookup(w,formed[i].id).charter.duty,oldBodies[i],
  'original founding witness remains immutable');
 A.equal(G.currentPurpose(G.lookup(w,formed[i].id)),
  examples[i].revised);
 const e=G.lookup(w,formed[i].id);
 A.equal(G.currentPurpose(e,{day:e.purposeHistory[0].day}),
  oldBodies[i], 'public may not see an undelivered new declaration');
 A.equal(G.currentPurpose(e,{day:e.purposeHistory[0].day+2}),
  examples[i].revised, 'the original two-day public release is respected');
 A.equal(G.validate(e),true);
}
A.equal(s.player.coins,originalCoins);
A.equal(s.rngState,originalRng,'no chosen dice are generated by public restatement');
A.equal(w.emergentGroups.rngState,worldRng,'independent group RNG is unchanged');
A.equal(w.groupMemberAgency?.rngState,memberRng,
 'independent person agency is never automatically treated as consent');
const status=R.act(s,{system:'social',operation:'groupPurposeHistory',
 params:{groupId}});
A.equal(status.foundingPurpose,examples[0].purpose);
A.equal(status.founderDeclarationNow,examples[0].revised);
A.equal(status.revisions.length,1);
A.equal(status.notMemberConsensus,true);
A.equal(status.noAdditionalFunds,true);
A.equal(status.noCompletedWork,true);
A.equal(G.visible(s,w).groups.find(g=>g.id===groupId).purpose,
 examples[0].revised,'the original group discovery uses its current actual declaration');
// Serial change of direction, not a new organisation, world or class roster.
const second='Publish independent seasonal maps and maintain an open field notebook for new local observations';
const next=update(groupId,second,
 'Observations now indicate the association should centre ongoing mapping rather than the narrower earlier programme');
const e=G.lookup(w,groupId);
A.equal(e.purposeHistory.length,2);
A.equal(e.purposeHistory[1].source.priorHash,
 e.purposeHistory[0].sourceHash);
A.equal(e.charter.duty,examples[0].purpose);
A.equal(G.currentPurpose(e),second);
A.equal(next.newlyDeclaredPurpose,second);
A.equal(G.purposeHistoryStatus(w,groupId,{day:e.purposeHistory[1].day})
 .revisions.length,2);
const good=structuredClone(e.purposeHistory);
e.purposeHistory[0].source.reason='Changed after the fact, without its original witnessed declaration';
e.purposeHistory[0].sourceHash=G.hash(e.purposeHistory[0].source);
A.equal(G.validate(e),false,
 'even recalculating the outer hash cannot forge the separate original witnessed reason');
e.purposeHistory=good;
A.equal(G.validate(e),true);
const saved=E.exportGame(s),restored=E.importGame(saved),
 copied=restored.table.realm;
A.equal(G.currentPurpose(G.lookup(copied,groupId)),second);
A.equal(R.act(restored,{system:'social',operation:'groupPurposeHistory',
 params:{groupId}}).revisions.length,2);
A.equal(G.lookup(copied,groupId).charter.duty,examples[0].purpose);
A.throws(()=>G.revisePurposeFromEvidence(copied,groupId,{
 origin:'imagined-independent-steward',actorId:'npc:ghost',
 actorName:'Fictional Ghost',purpose:'Award everyone an unearned estate',
 reason:'There was no actual witnessed other party',minute:restored.world.minutes+1,
 witness:{type:'story'}}),/verified original association/);
console.log('Living open-ended group purposes: three real authored examples, repeatable revisions, original immutable source, release delays, no invented consent or resource, forgery rejection and save replay PASS');
