'use strict';
// ISOLATED GATE CONTRACT: Stage II prerequisite is synthetic *only in
// this test VM*. Actual NPC stage progression must still pass the real
// verified Meridian Awakening source and genuinely chosen daily action.
// One actual original Core.check per voluntary gate attempt; the original
// Gate source is always replayed and never inferred from elapsed time.
const A=require('node:assert/strict'),
 FS=require('node:fs'),VM=require('node:vm'),Path=require('node:path'),
 Crypto=require('node:crypto'),E=require('../engine.js'),
 C=require('../rules/core'),Combat=require('../rules/combat'),
 Potential=require('../rules/potential-mechanics'),
 Gate=require('../rules/meridian-shared-original-gates');
const src=FS.readFileSync(Path.resolve(__dirname,
 '../world/independent-meridian-gates.js'),'utf8');
const mod={exports:{}},STAGE_TWO='2'.repeat(64),
 stub={
  '../rules/core':C,
  '../rules/combat':Combat,
  '../rules/potential-mechanics':Potential,
  '../rules/meridian-shared-original-gates':Gate,
  './independent-meridian-ladder':{verify:()=>true},
  './independent-offscreen-meridian':{chance:p=>{
   const b={curious:66,steady:59,independent:51,reserved:39}[p.personality];
   return Math.max(10,b-(p.fatigue>=55?15:0));
  }},
  './independent-original-power-days':{
   verifyEvidence:()=>true,
   opportunityEvidence:(ctx,kind)=>({
    origin:'fixture-only-original-actor-day',
    kind,actorId:ctx.actor.actorId,privatePhysicalSite:ctx.site,
    originalWorkDay:ctx.workDay,
    originalShiftHash:ctx.originalShiftHash})
  }
 };
VM.runInNewContext(src,{module:mod,structuredClone,console,
 require:id=>{
  if(id==='node:crypto')return Crypto;
  if(id==='./independent-meridian-sea')
   throw Error('The separately original Stage IV Sea must not be generated by one Gate');
  if(!Object.hasOwn(stub,id))throw Error('Unexpected Gate fixture dependency '+id);
  return stub[id];
 }});
const Original=mod.exports;
const s=E.newGame({name:'Disposable Gate owner contract',seed:964811});
const p={id:'disposable_person',actorId:'emergent:disposable_person',
 originHash:'o'.repeat(64),personality:'curious',fatigue:0,
 rngState:0x91e10da5,
 mechanicalFoundation:{seal:'f'.repeat(64),
  baselineAttributes:{str:10,dex:10,con:13,int:12,wis:17,cha:10},
  unassessedPotential:{gateStability:75}},
 meridianTraining:{foundationQuality:'Firm'},
 originalMeridianLadder:{stage:2,originalStageTwoSourceHash:STAGE_TWO,
  awakening:{lastAttemptDay:0},
  energy:{maxQi:100,currentQi:100,flow:15,recovery:5,
   originalCapacityOwner:'rules/build.js:meridianProfile'}}};
const body={status:'ok',stamina:40,maxStamina:40,wounds:[0,0,0],
 npcOrigin:{seal:'b'.repeat(64)}};
s.table.combatants['npc_'+p.id]=body;
A.equal(Original.verify(s,p),true);
let found=null,opened=false;
for(let day=1;day<=60;day++){
 const before=s.rngState,log=JSON.stringify(s.log);
 s.world.minutes=(day+1)*1440;
 const ret=Original.afterDaily(s,{actor:p,body,workDay:day,
  site:'crossing',originalShiftHash:'s'.repeat(64)});
 A.equal(s.rngState,before,'Separate private human check never draws the player RNG');
 A.equal(JSON.stringify(s.log),log,'Private off-screen Gate check never leaks into player-visible story');
 A.equal(Original.verify(s,p),true,'Exact original Gate receipts replay after each genuine check');
 if(ret){
  A.equal(ret.gateNumber,1);
  A.equal(ret.privateToGM,true);
  const q=p.originalMeridianGates.sessions.at(-1).source;
  A.equal(q.originalStageTwoSourceHash,STAGE_TWO);
  A.equal(q.originalSkillRankBonus,0);
  A.equal(q.originalForceChoice,false);
  A.equal(q.actualDC,Gate.gateSpec(1).actualDC);
  A.equal(q.requiredPoints,3);
  A.equal(q.gateBand,'Lower');
  A.equal(q.transition,false);
  A.equal(q.noInventedTechniqueOrOtherStage,true);
  if(q.accepted){
   A.equal(q.actualMinutes,180);
   A.ok(q.check.roll>=1&&q.check.roll<=20);
   A.equal(q.check.dc,13);
   A.equal(q.check.modifier,Gate.foundationBonus('Firm')+
    Math.floor((p.mechanicalFoundation.baselineAttributes.wis-10)/2)+
    Potential.bonus(75));
  }else A.equal(q.actualMinutes,5);
  found=q;
 }
 if(p.originalMeridianGates?.gates.length){
  opened=true;break;
 }
}
A.ok(found,'Real original core/check from independently accepted or declined Gate days');
A.equal(opened,true,'A genuine original Gate opening is possible with the distinct Stage II prerequisite');
A.equal(p.originalMeridianGates.stage,3);
A.equal(p.originalMeridianGates.gates[0].number,1);
A.ok(['Perfect','Sound','Flawed'].includes(
 p.originalMeridianGates.gates[0].quality));
A.deepEqual(Gate.verifiedGates([{number:1,band:'Lower',
 quality:p.originalMeridianGates.gates[0].quality}]),
 {Perfect:p.originalMeridianGates.gates[0].quality==='Perfect'?1:0,
  Sound:p.originalMeridianGates.gates[0].quality==='Sound'?1:0,
  Flawed:p.originalMeridianGates.gates[0].quality==='Flawed'?1:0});
A.equal(Original.verify(s,p),true);
const forged=structuredClone(p),
 row=forged.originalMeridianGates.sessions.at(-1);
row.source.actualDC=2;
row.seal=Crypto.createHash('sha256').
 update(JSON.stringify(row.source)).digest('hex');
A.equal(Original.verify(s,forged),false,
 'Even re-sealed independent source with fake DC cannot grant a Gate');
for(const n of [36,72,108]){
 const r=Gate.gateSpec(n);
 A.equal(r.transition,true);
 A.equal(r.actualDC,r.baseDC+3);
}
A.equal(s.player.meridian.stage,0);
console.log('Isolated original independent NPC 108-Gate source contract PASS: original separate Stage II required, real private acceptance/check, correct Gate 1, exact replay and forged DC rejection; synthetic earlier prerequisite restricted to test VM');
